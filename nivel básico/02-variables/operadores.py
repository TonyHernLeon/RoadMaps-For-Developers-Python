"""Modulo de operadores Matemáticos"""

# - Constantes
NUM_1 = 4
NUM_2 = 5


# Suma
print(f"La suma entre {NUM_1} y {NUM_2} es: {NUM_1 + NUM_2}")
# Resta
print(f"La resta entre {NUM_1} y {NUM_2} es: {NUM_1 - NUM_2}")
# Multiplcación
print(f"La multiplicación entre {NUM_1} y {NUM_2} es: {NUM_1 * NUM_2}")
# Divsion
print(f"La división entre {NUM_1} y {NUM_2} es: {NUM_1 / NUM_2}")
# Divsion
print(f"La división (con truncamiento) entre {NUM_1} y {NUM_2} es: {NUM_1 // NUM_2}")
# Modulo
print(f"El módulo de {NUM_1} y {NUM_2} es: {NUM_1 % NUM_2}")
# Elevación
print(f"El {NUM_1} elevado a {NUM_2} es: {NUM_1 ** NUM_2}")
# Raiz Cuadrada
print(f"La raíz cuadrada de {NUM_1} es: {NUM_1 ** 0.5}")
